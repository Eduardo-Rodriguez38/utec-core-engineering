#!/usr/bin/env python3
"""Module with basic calculator functions."""


def add(a, b):
    """Return a + b."""
    return (a + b)


def sub(a, b):
    """Return a - b."""
    return (a - b)


def mul(a, b):
    """Return a * b."""
    return (a * b)


def div(a, b):
    """Return the integer division of a by b."""
    return int(a / b)
